export function mapVideo(raw: unknown): Video {
  const r = toCamelDeep<RecordAny>(raw as RecordAny);
  const createdAt = asString(r.createdAt);
  const channelId = asString(r.channelId);
  return {
    id: asString(r.id),
    channelId,
    channel: channelId
      ? {
          id: channelId,
          ownerId: asString(r.channelOwnerId),
          handle: asString(r.channelHandle),
          name: asString(r.channelName),
          avatarUrl: asString(r.channelAvatarUrl || r.channelAvatar) || undefined,
          subscriberCount: asNumber(r.channelSubscriberCount),
          videoCount: asNumber(r.channelVideoCount),
          isVerified: Boolean(r.channelIsVerified),
          createdAt,
          updatedAt: createdAt,
        }
      : undefined,
    title: asString(r.title),
    description: asString(r.description),
    videoType: r.videoType,
    durationSeconds: asNumber(r.durationSeconds),
    thumbnailUrl: asString(r.thumbnailUrl),
    previewUrl: r.previewUrl ? asString(r.previewUrl) : undefined,
    hlsMasterUrl: r.hlsMasterUrl ? asString(r.hlsMasterUrl) : undefined,
    visibility: r.visibility,
    status: r.status,
    viewCount: asNumber(r.viewCount),
    likeCount: asNumber(r.likeCount),
    dislikeCount: asNumber(r.dislikeCount),
    commentCount: asNumber(r.commentCount),
    tags: asArray<string>(r.tags),
    category: asString(r.category),
    isAgeRestricted: Boolean(r.isAgeRestricted),
    sources: asArray(r.sources).map(mapVideoSource),
    chapters: asArray(r.chapters).map(mapVideoChapter),
    captions: asArray(r.captions).map((c, i) => mapVideoCaption(c, i)),
    publishedAt: r.publishedAt ? asString(r.publishedAt) : undefined,
    scheduledAt: r.scheduledAt ? asString(r.scheduledAt) : undefined,
    createdAt,
    updatedAt: asString(r.updatedAt, createdAt),
  };
}


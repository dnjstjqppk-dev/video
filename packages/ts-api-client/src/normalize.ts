// Server stores KRW minor units (x100) in *Cents fields; UI works in won.
const centsToWon = (cents: unknown): number => Math.round(asNumber(cents) / 100);

export function mapCampaign(raw: unknown): AdCampaign {
  const r = toCamelDeep<RecordAny>(raw as RecordAny);
  const impressions = asNumber(r.impressions);
  const createdAt = asString(r.createdAt);
  return {
    id: asString(r.id),
    advertiserId: asString(r.advertiserId),
    organizationId: asString(r.organizationId),
    name: asString(r.name),
    format: r.format,
    status: r.status,
    dailyBudget: centsToWon(r.dailyBudgetCents ?? r.dailyBudget),
    totalBudget: centsToWon(r.totalBudgetCents ?? r.totalBudget),
    spentAmount: centsToWon(r.spentCents ?? r.spentAmount),
    cpmBid: centsToWon(r.cpmBidCents ?? r.cpmBid),
    cpcBid: centsToWon(r.cpcBidCents ?? r.cpcBid),
    targetCategories: asArray<string>(r.targetCategories),
    targetCountries: asArray<string>(r.targetCountries),
    startDate: asString(r.startDate || r.startAt),
    endDate: asString(r.endDate || r.endAt),
    impressions,
    clicks: asNumber(r.clicks),
    views: asNumber(r.views, impressions),
    createdAt,
    updatedAt: asString(r.updatedAt, createdAt),
  };
}


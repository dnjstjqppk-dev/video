<script setup lang="ts">
useSeoMeta({
  title: 'Video Subtitles & Captions — Creator Studio'
})

interface SubtitleTrack {
  id: string
  language: string
  code: string
  format: 'vtt' | 'srt'
  isAutoGenerated: boolean
  updatedAt: string
}

interface VideoSubtitles {
  id: string
  title: string
  thumbnailUrl: string
  duration: string
  tracks: SubtitleTrack[]
}

const videos = ref<VideoSubtitles[]>([
  {
    id: 'vid_arch_2026',
    title: 'Building a 10M Concurrent Viewer Global Video Platform with Go 1.24',
    thumbnailUrl: 'https://images.unsplash.com/photo-1518770660439-4636190af475?w=200',
    duration: '42:15',
    tracks: [
      { id: 'sub_kr', language: '한국어 (기본)', code: 'ko', format: 'vtt', isAutoGenerated: false, updatedAt: '2026-10-25' },
      { id: 'sub_en', language: '영어 (미국)', code: 'en', format: 'vtt', isAutoGenerated: false, updatedAt: '2026-10-26' },
      { id: 'sub_ja', language: '일본어', code: 'ja', format: 'vtt', isAutoGenerated: true, updatedAt: '2026-10-26' }
    ]
  },
  {
    id: 'vid_ai_agents',
    title: 'Multimodal Video Indexing with Audio-Visual Fingerprints & Vector Embeddings',
    thumbnailUrl: 'https://images.unsplash.com/photo-1618005182384-a83a8bd57fbe?w=200',
    duration: '28:40',
    tracks: [
      { id: 'sub_kr_2', language: '한국어 (기본)', code: 'ko', format: 'vtt', isAutoGenerated: false, updatedAt: '2026-10-27' },
      { id: 'sub_en_2', language: '영어 (미국)', code: 'en', format: 'vtt', isAutoGenerated: true, updatedAt: '2026-10-27' }
    ]
  }
])

const uploadModalOpen = ref(false)
const selectedVideo = ref<VideoSubtitles | null>(null)
const newLanguage = ref('es')
const fileUploaded = ref(false)
const toastMessage = ref('')

function openUploadModal(v: VideoSubtitles) {
  selectedVideo.value = v
  newLanguage.value = 'es'
  fileUploaded.value = false
  uploadModalOpen.value = true
}

function handleAddTrack() {
  if (!selectedVideo.value) return
  selectedVideo.value.tracks.push({
    id: `sub_${newLanguage.value}_${Date.now()}`,
    language: newLanguage.value === 'es' ? '스페인어' : '프랑스어',
    code: newLanguage.value,
    format: 'vtt',
    isAutoGenerated: false,
    updatedAt: new Date().toISOString().split('T')[0] || '2026-10-30'
  })
  uploadModalOpen.value = false
  toastMessage.value = '새 다국어 WebVTT 자막 트랙이 성공적으로 추가되었습니다.'
  setTimeout(() => {
    toastMessage.value = ''
  }, 4000)
}
</script>

<template>
  <div class="space-y-6">
    <div class="flex items-center justify-between">
      <div>
        <h1 class="text-2xl font-extrabold text-white">채널 자막 관리 (Subtitles & Captions)</h1>
        <p class="mt-1 text-xs text-neutral-400">
          다국어 WebVTT/SRT 자막 업로드 및 인공지능 Whisper 자동 음성 인식 자막 관리
        </p>
      </div>
    </div>

    <div
      v-if="toastMessage"
      class="rounded-xl border border-emerald-500/30 bg-emerald-500/10 p-4 text-xs font-semibold text-emerald-300"
    >
      {{ toastMessage }}
    </div>

    <div class="divide-y divide-white/5 rounded-2xl border border-white/10 bg-[#161922]">
      <div
        v-for="v in videos"
        :key="v.id"
        class="flex flex-col gap-4 p-6 md:flex-row md:items-start md:justify-between"
      >
        <div class="flex gap-4">
          <img
            :src="v.thumbnailUrl"
            :alt="v.title"
            class="h-20 w-32 rounded-xl object-cover"
          />
          <div>
            <h2 class="text-sm font-bold text-white">{{ v.title }}</h2>
            <div class="mt-1 text-xs text-neutral-400">재생 시간: {{ v.duration }}</div>

            <!-- Existing Language Badges -->
            <div class="mt-3 flex flex-wrap gap-2">
              <span
                v-for="tr in v.tracks"
                :key="tr.id"
                class="flex items-center gap-1.5 rounded-lg border border-white/10 bg-white/5 px-2.5 py-1 text-xs text-neutral-300"
              >
                <span>{{ tr.language }}</span>
                <span class="rounded bg-neutral-700 px-1 text-[10px] text-neutral-400 uppercase">{{ tr.format }}</span>
                <span v-if="tr.isAutoGenerated" class="text-[10px] text-sky-400 font-semibold">(자동생성)</span>
              </span>
            </div>
          </div>
        </div>

        <button
          type="button"
          class="self-start rounded-xl border border-white/15 bg-white/5 px-3.5 py-2 text-xs font-bold text-white transition hover:bg-white/15"
          @click="openUploadModal(v)"
        >
          + 언어 추가
        </button>
      </div>
    </div>

    <!-- Upload Subtitle Modal -->
    <div
      v-if="uploadModalOpen"
      class="fixed inset-0 z-50 flex items-center justify-center bg-black/80 p-4 backdrop-blur-sm"
    >
      <div class="w-full max-w-md rounded-2xl border border-white/15 bg-[#1B1F2B] p-6 text-white shadow-2xl">
        <h3 class="text-lg font-extrabold">새 자막 트랙 추가</h3>
        <p class="mt-1 text-xs text-neutral-400">
          동영상에 적용할 WebVTT 또는 SRT 자막 파일을 업로드하세요.
        </p>

        <div class="mt-4 space-y-4">
          <div>
            <label class="block text-xs font-semibold text-neutral-300">자막 언어</label>
            <select
              v-model="newLanguage"
              class="mt-1 w-full rounded-xl border border-white/15 bg-[#12151E] p-2.5 text-xs text-white outline-none"
            >
              <option value="es">스페인어 (Spanish)</option>
              <option value="fr">프랑스어 (French)</option>
              <option value="de">독일어 (German)</option>
              <option value="zh">중국어 (Chinese)</option>
            </select>
          </div>

          <div class="rounded-xl border border-dashed border-white/20 p-6 text-center">
            <div class="text-2xl">📄</div>
            <div class="mt-2 text-xs font-semibold text-white">.vtt 또는 .srt 파일 드래그 앤 드롭</div>
            <button
              type="button"
              class="mt-3 rounded-lg bg-white/10 px-3 py-1.5 text-xs font-medium text-neutral-300 hover:bg-white/20"
              @click="fileUploaded = true"
            >
              {{ fileUploaded ? '✓ sample_subtitles.vtt 선택됨' : '파일 찾아보기' }}
            </button>
          </div>
        </div>

        <div class="mt-6 flex justify-end gap-3">
          <button
            type="button"
            class="rounded-xl border border-white/15 px-4 py-2 text-xs font-bold text-neutral-300 hover:bg-white/5"
            @click="uploadModalOpen = false"
          >
            취소
          </button>
          <button
            type="button"
            class="rounded-xl bg-[#FF0033] px-5 py-2 text-xs font-bold text-white transition hover:bg-[#D9002B] disabled:opacity-50"
            :disabled="!fileUploaded"
            @click="handleAddTrack"
          >
            자막 게시
          </button>
        </div>
      </div>
    </div>
  </div>
</template>

